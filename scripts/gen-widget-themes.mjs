// Auto-register widget themes dari nama file (generik, dipakai semua widget).
// Cara pakai:
//   node scripts/gen-widget-themes.mjs --dir=app/widgets/chat/themes --props=ChatThemeProps --map=chatThemeComponents --options=CHAT_THEME_OPTIONS --default=CHAT_THEME_DEFAULT
// Konvensi tiap file theme (mis. Neon.tsx):
//   export const themeMeta = { value: 'neon', label: 'Neon - Deskripsi' } as const;
//   export default function ApaSaja(props: XxxThemeProps) { ... }
// File tanpa themeMeta (helper/utils) otomatis di-skip.
// Hasil: themes/registry.tsx di-generate ulang — JANGAN edit manual.

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, dirname, basename } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

function arg(name) {
  const m = process.argv.find((a) => a.startsWith(`--${name}=`));
  return m ? m.slice(name.length + 3) : null;
}

const dirArg = arg("dir");
const propsType = arg("props");
const mapName = arg("map");
const optionsName = arg("options");
const defaultName = arg("default");

if (!dirArg || !propsType || !mapName || !optionsName || !defaultName) {
  console.error("Usage: node scripts/gen-widget-themes.mjs --dir=app/widgets/chat/themes --props=ChatThemeProps --map=chatThemeComponents --options=CHAT_THEME_OPTIONS --default=CHAT_THEME_DEFAULT");
  process.exit(1);
}

const dir = join(root, dirArg);
const out = join(dir, "registry.tsx");

// wajib ada `export const themeMeta = { value: 'x', label: 'y' }`
function parseMeta(src, file) {
  const m = src.match(/export\s+const\s+themeMeta\s*=\s*\{\s*value\s*:\s*['"]([^'"]+)['"]\s*,\s*label\s*:\s*['"]([^'"]+)['"]/);
  if (!m) return null;
  if (!/export\s+default\s+(function|class)/.test(src)) {
    console.warn(`[gen:widget-themes] SKIP ${file} — ada themeMeta tapi tidak ada default export component`);
    return null;
  }
  return { value: m[1], label: m[2] };
}

const files = readdirSync(dir)
  .filter((f) => (f.endsWith(".tsx") || f.endsWith(".ts")) && f !== "registry.tsx" && f !== "types.ts")
  .sort();

const entries = [];
for (const f of files) {
  const meta = parseMeta(readFileSync(join(dir, f), "utf8"), f);
  if (!meta) continue; // file helper (tanpa themeMeta) otomatis di-skip
  if (!/^[a-z0-9_-]+$/i.test(meta.value)) {
    console.warn(`[gen:widget-themes] SKIP ${f} — themeMeta.value "${meta.value}" tidak valid`);
    continue;
  }
  const name = basename(f, ".tsx").replace(/\.ts$/, "");
  entries.push({ ...meta, name, file: f });
}

const seen = new Map();
for (const e of entries) {
  if (seen.has(e.value)) {
    console.error(`[gen:widget-themes] ERROR value ganda "${e.value}" dari ${seen.get(e.value)} dan ${e.file}. Ganti themeMeta.value salah satu.`);
    process.exit(1);
  }
  seen.set(e.value, e.file);
}

entries.sort((a, b) => a.value.localeCompare(b.value));
const fallback = entries.find((e) => e.value === "standard") || entries[0];

const lines = [
  "// AUTO-GENERATED by `npm run gen:themes` — JANGAN edit manual.",
  "// Tambah theme baru: buat file themes/NamaTema.tsx + `export const themeMeta = {...}`, lalu restart dev.",
  "",
  'import type { ComponentType } from "react";',
  `import type { ${propsType} } from "./types";`,
  ...entries.map((e) => `import ${e.name}Theme from "./${e.name}";`),
  "",
  `export const ${mapName}: Record<string, ComponentType<${propsType}>> = {`,
  ...entries.map((e) => `  ${JSON.stringify(e.value)}: ${e.name}Theme,`),
  "};",
  "",
  `export const ${optionsName} = [`,
  ...entries.map((e) => `  { value: ${JSON.stringify(e.value)}, label: ${JSON.stringify(e.label)} },`),
  "] as const;",
  "",
  `export const ${defaultName} = ${JSON.stringify(fallback ? fallback.value : "standard")};`,
  "",
];

writeFileSync(out, lines.join("\n"));
console.log(`[gen:widget-themes:${dirArg}] OK — ${entries.length} theme: ${entries.map((e) => e.value).join(", ")}`);
