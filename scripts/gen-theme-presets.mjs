// Auto-register theme presets dari nama file.
// Cara pakai: taruh file baru di app/overlay/themes/presets/namaTema.ts
// (export default defineTheme({...})), lalu jalankan:
//   npm run gen:themes
// (otomatis jalan tiap `npm run dev` / `npm run build` via predev/prebuild)
// File presets/index.ts di-generate ulang — JANGAN edit manual.

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, dirname, basename } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "app", "overlay", "themes", "presets");
const out = join(dir, "index.ts");

// nama file -> key registry: "my-theme.ts" => "myTheme", "neon.ts" => "neon"
function toKey(file) {
  const base = basename(file, ".ts");
  const camel = base.replace(/[-_]+([A-Za-z0-9])/g, (_, c) => c.toUpperCase());
  if (!/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(camel)) return null;
  return camel;
}

// baca field `category: "..."` dari source (tanpa import — biar script tanpa deps)
function parseCategory(src) {
  const m = src.match(/category\s*:\s*["']([A-Za-z0-9_-]+)["']/);
  return m ? m[1] : "core";
}

const files = readdirSync(dir)
  .filter((f) => f.endsWith(".ts") && f !== "index.ts")
  .sort();

const entries = [];
for (const f of files) {
  const key = toKey(f);
  if (!key) {
    console.warn(`[gen:themes] SKIP ${f} — nama file tidak valid sebagai key (pakai huruf/angka/-/_, mis. my-theme.ts)`);
    continue;
  }
  const mod = `./${basename(f, ".ts")}`;
  const category = parseCategory(readFileSync(join(dir, f), "utf8"));
  entries.push({ key, mod, file: f, category });
}

// deteksi key ganda (mis. my-theme.ts vs myTheme.ts)
const seen = new Map();
for (const e of entries) {
  if (seen.has(e.key)) {
    console.error(`[gen:themes] ERROR key ganda "${e.key}" dari ${seen.get(e.key)} dan ${e.file}. Rename salah satu file.`);
    process.exit(1);
  }
  seen.set(e.key, e.file);
}

// kelompok kategori sesuai urutan kemunculan, key di dalamnya terurut
const catOrder = [];
const catMap = new Map();
for (const e of [...entries].sort((a, b) => a.key.localeCompare(b.key))) {
  if (!catMap.has(e.category)) {
    catMap.set(e.category, []);
    catOrder.push(e.category);
  }
  catMap.get(e.category).push(e.key);
}

const lines = [
  "// AUTO-GENERATED by `npm run gen:themes` — JANGAN edit manual.",
  "// Tambah tema baru: buat file presets/namaTema.ts (export default defineTheme({...})), lalu restart dev / jalankan npm run gen:themes.",
  "",
  'import type { ThemePresetMap } from "../types";',
  ...entries.map((e) => `import ${e.key} from "${e.mod}";`),
  "",
  "export const themePresets: ThemePresetMap = {",
  ...entries.map((e) => `  ${e.key},`),
  "};",
  "",
  "// Optional: export by category for filtered UI (dibaca dari field `category` tiap preset)",
  "export const themeCategories = {",
  ...catOrder.map((c) => `  ${JSON.stringify(c)}: [${catMap.get(c).map((k) => `"${k}"`).join(", ")}],`),
  "} as const;",
  "",
];

writeFileSync(out, lines.join("\n"));
console.log(`[gen:themes] OK — ${entries.length} preset: ${entries.map((e) => e.key).join(", ")}`);
